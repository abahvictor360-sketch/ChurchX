/**
 * Generates types/database.ts (Supabase "Database" shape) by introspecting a
 * PostgreSQL database that has the migrations applied.
 *
 *   DATABASE_URL=postgres://... npx tsx scripts/gen-db-types.ts
 *
 * Equivalent to `supabase gen types typescript`, but works without Docker.
 * If you use the Supabase CLI you can replace this with:
 *   supabase gen types typescript --linked --schema public > types/database.ts
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { Client } from "pg";

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("DATABASE_URL is required");
  process.exit(1);
}

const scalar: Record<string, string> = {
  uuid: "string",
  text: "string",
  bpchar: "string",
  varchar: "string",
  citext: "string",
  date: "string",
  time: "string",
  timetz: "string",
  timestamp: "string",
  timestamptz: "string",
  interval: "string",
  int2: "number",
  int4: "number",
  int8: "number",
  float4: "number",
  float8: "number",
  numeric: "number",
  bool: "boolean",
  json: "Json",
  jsonb: "Json",
  void: "undefined",
};

function tsType(udt: string): string {
  if (udt.startsWith("_")) return `${tsType(udt.slice(1))}[]`;
  return scalar[udt] ?? "unknown";
}

async function main() {
  const db = new Client({ connectionString: url });
  await db.connect();

  const { rows: cols } = await db.query<{
    table_name: string;
    column_name: string;
    udt_name: string;
    is_nullable: string;
    column_default: string | null;
    is_generated: string;
    is_view: boolean;
  }>(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, c.is_generated,
           t.table_type = 'VIEW' as is_view
      from information_schema.columns c
      join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
     where c.table_schema = 'public'
     order by c.table_name, c.ordinal_position`);

  const { rows: fks } = await db.query<{
    table_name: string;
    constraint_name: string;
    columns: string[];
    ref_table: string;
    ref_columns: string[];
    one_to_one: boolean;
  }>(`
    select cl.relname as table_name, con.conname as constraint_name,
           array(select a.attname from unnest(con.conkey) with ordinality k(n, i)
                 join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.i)::text[] as columns,
           rcl.relname as ref_table,
           array(select a.attname from unnest(con.confkey) with ordinality k(n, i)
                 join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.i)::text[] as ref_columns,
           exists (select 1 from pg_constraint u where u.conrelid = con.conrelid and u.contype in ('u', 'p')
                     and u.conkey::int[] @> con.conkey::int[] and u.conkey::int[] <@ con.conkey::int[]) as one_to_one
      from pg_constraint con
      join pg_class cl on cl.oid = con.conrelid
      join pg_namespace ns on ns.oid = cl.relnamespace
      join pg_class rcl on rcl.oid = con.confrelid
      join pg_namespace rns on rns.oid = rcl.relnamespace
     where con.contype = 'f' and ns.nspname = 'public' and rns.nspname = 'public'
     order by cl.relname, con.conname`);

  const { rows: fns } = await db.query<{
    proname: string;
    arg_names: string[] | null;
    arg_types: string[];
    arg_modes: string[] | null;
    n_defaults: number;
    ret_type: string;
    retset: boolean;
  }>(`
    select p.proname, p.proargnames as arg_names,
           array(select t.typname from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality a(oid, i)
                 join pg_type t on t.oid = a.oid order by a.i)::text[] as arg_types,
           p.proargmodes::text[] as arg_modes, p.pronargdefaults as n_defaults,
           rt.typname as ret_type, p.proretset as retset
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
      join pg_type rt on rt.oid = p.prorettype
     where n.nspname = 'public' and p.prokind = 'f' and rt.typname <> 'trigger'
     order by p.proname`);

  await db.end();

  const tables = new Map<string, typeof cols>();
  for (const c of cols) {
    if (!tables.has(c.table_name)) tables.set(c.table_name, []);
    tables.get(c.table_name)!.push(c);
  }

  const out: string[] = [];
  out.push("// Generated by scripts/gen-db-types.ts — do not edit by hand.");
  out.push("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
  out.push("");
  out.push("export type Database = {");
  out.push("  public: {");
  out.push("    Tables: {");
  for (const [name, columns] of tables) {
    if (columns[0].is_view) continue;
    out.push(`      ${name}: {`);
    out.push("        Row: {");
    for (const c of columns) out.push(`          ${c.column_name}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`);
    out.push("        };");
    for (const kind of ["Insert", "Update"] as const) {
      out.push(`        ${kind}: {`);
      for (const c of columns) {
        if (c.is_generated === "ALWAYS") {
          out.push(`          ${c.column_name}?: never;`);
          continue;
        }
        const optional = kind === "Update" || c.is_nullable === "YES" || c.column_default !== null;
        out.push(`          ${c.column_name}${optional ? "?" : ""}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`);
      }
      out.push("        };");
    }
    out.push("        Relationships: [");
    for (const fk of fks.filter((f) => f.table_name === name)) {
      out.push("          {");
      out.push(`            foreignKeyName: ${JSON.stringify(fk.constraint_name)};`);
      out.push(`            columns: ${JSON.stringify(fk.columns)};`);
      out.push(`            isOneToOne: ${fk.one_to_one};`);
      out.push(`            referencedRelation: ${JSON.stringify(fk.ref_table)};`);
      out.push(`            referencedColumns: ${JSON.stringify(fk.ref_columns)};`);
      out.push("          },");
    }
    out.push("        ];");
    out.push("      };");
  }
  out.push("    };");
  out.push("    Views: { [_ in never]: never };");
  out.push("    Functions: {");
  for (const f of fns) {
    const names = f.arg_names ?? [];
    const modes = f.arg_modes ?? f.arg_types.map(() => "i");
    const inArgs: string[] = [];
    const outCols: string[] = [];
    const inputIdx = modes.map((m, i) => (m === "i" || m === "b" ? i : -1)).filter((i) => i >= 0);
    const firstDefault = inputIdx.length - f.n_defaults;
    inputIdx.forEach((idx, pos) => {
      inArgs.push(`${names[idx]}${pos >= firstDefault ? "?" : ""}: ${tsType(f.arg_types[idx])}`);
    });
    modes.forEach((m, i) => {
      if (m === "t" || m === "o") outCols.push(`${names[i]}: ${tsType(f.arg_types[i])} | null`);
    });
    let ret: string;
    if (outCols.length) ret = `{ ${outCols.join("; ")} }[]`;
    else ret = `${tsType(f.ret_type)}${f.retset ? "[]" : ""}`;
    out.push(`      ${f.proname}: {`);
    out.push(`        Args: ${inArgs.length ? `{ ${inArgs.join("; ")} }` : "Record<PropertyKey, never>"};`);
    out.push(`        Returns: ${ret};`);
    out.push("      };");
  }
  out.push("    };");
  out.push("    Enums: { [_ in never]: never };");
  out.push("    CompositeTypes: { [_ in never]: never };");
  out.push("  };");
  out.push("};");
  out.push("");
  out.push('type PublicSchema = Database["public"];');
  out.push('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];');
  out.push('export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];');
  out.push('export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];');
  out.push("");

  const target = path.resolve(__dirname, "../types/database.ts");
  writeFileSync(target, out.join("\n"));
  console.log(`Wrote ${target}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
